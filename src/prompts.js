/**
 * Возвращает массив сообщений для Chat Completions API.
 * @param {string} mode  - ключ режима
 * @param {string} input - текст пользователя
 * @param {object} [options]
 * @param {Array<{role: string, content: string}>} [options.history]
 *        предыдущие сообщения диалога
 * @param {string} [options.context] - фрагменты документации (режим docs)
 */
function buildMessages(mode, input, { history = [], context = '' } = {}) {
  const template = MODES[mode];
  if (!template) {
    throw new Error(`Неизвестный режим: ${mode}`);
  }
  return [
    { role: 'system', content: template.system },
    ...history,
    { role: 'user', content: template.user(input, context) }
  ];
}

module.exports = { MODES, buildMessages };
